/** Raw dictionaries — handy for coverage tests and tooling. */
export const FEATURE_STRINGS = D

/** Translate a feature key. Falls back: lang → English → humanised key. */
export function tr(lang, key, vars = {}) {
  const dict = D[lang] || D.en
  let s = dict[key] ?? D.en[key]
  if (s === undefined) s = key.split('.').pop()
  s = String(s)
  Object.entries(vars || {}).forEach(([k, v]) => { s = s.split(`{${k}}`).join(String(v)) })
  return s
}

export default tr
